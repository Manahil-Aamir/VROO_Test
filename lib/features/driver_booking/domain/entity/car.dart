class CarEntity {
  final String company;
  final String model;
  final String color;
  final String numberPlate;
  final double mileage;
  final bool isVerified;

  CarEntity({
    required this.company,
    required this.model,
    required this.color,
    required this.numberPlate,
    required this.mileage,
    required this.isVerified,
  });
}
